#!/usr/bin/env python3
"""Generate the notices for the module packages selected by release builds."""
# cspell:words LICENCE GOENV GOWORK

import argparse
import json
import os
from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parents[1]
NOTICE = re.compile(r"^(?:LICENSE|LICENCE|COPYING|COPYRIGHT|NOTICE|PATENTS)(?:$|[._-])", re.I)
TEXT_SUFFIXES = {"", ".txt", ".md", ".rst"}
TARGETS = [(os_name, architecture) for os_name in ("linux", "darwin", "windows")
           for architecture in ("386", "amd64", "arm64") if (os_name, architecture) != ("darwin", "386")]


def go(*args, **settings):
    env = dict(os.environ, GOENV="off", GOWORK="off", GOFLAGS="", CGO_ENABLED="0", **settings)
    executable = env.get("JOBMAN_NOTICE_GO", "go")
    return subprocess.check_output([executable, *args], cwd=ROOT, env=env, text=True)


def packages(text):
    decoder = json.JSONDecoder()
    text = text.lstrip()
    while text:
        value, end = decoder.raw_decode(text)
        yield value
        text = text[end:].lstrip()


def generate():
    notices = {}
    for os_name, architecture in TARGETS:
        for package in packages(go("list", "-mod=readonly", "-deps", "-json", ".", GOOS=os_name, GOARCH=architecture)):
            module = package.get("Module")
            if not module or module.get("Main"):
                continue
            if module.get("Replace") or not module.get("Version"):
                raise ValueError("expected an immutable release module")
            identity = module["Path"] + "@" + module["Version"]
            root, directory = Path(module["Dir"]), Path(package["Dir"])
            directory.relative_to(root)
            while True:
                for path in directory.iterdir():
                    if path.is_file() and NOTICE.match(path.name) and path.suffix.lower() in TEXT_SUFFIXES:
                        notices[identity, path.relative_to(root).as_posix()] = path.read_text(encoding="utf-8")
                if directory == root:
                    break
                directory = directory.parent
    version, goroot = go("env", "GOVERSION", "GOROOT").splitlines()
    for name in ("LICENSE", "PATENTS"):
        notices[version, name] = (Path(goroot) / name).read_text(encoding="utf-8")
    lines = ["<!-- Generated by make gen-notices. -->", "# Third-party notices", "",
             "Upstream notices for the Control release dependencies.",
             "Each dependency retains its own license terms.", "", "<!-- cspell:disable -->", ""]
    for (identity, name), text in sorted(notices.items()):
        lines.extend([f"## {identity} · {name}", ""])
        lines.extend(("    " + line).rstrip() for line in text.splitlines())
        lines.append("")
    lines.extend(["<!-- cspell:enable -->", ""])
    return "\n".join(lines).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "THIRD_PARTY_NOTICES.md"
    generated = generate()
    if args.check:
        if path.read_bytes() != generated:
            parser.exit(1, "THIRD_PARTY_NOTICES.md is stale. Run make gen-notices.\n")
    else:
        path.write_bytes(generated)


if __name__ == "__main__":
    main()
